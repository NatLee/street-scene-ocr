"""Run the OCR engines on the benchmark images and write the scores to eval/results/.

    python eval/run.py                         # every installed engine, both image sets
    python eval/run.py --engines rapidocr      # just one engine

Each engine goes through the same service code as the web page (same resizing, same threshold),
so the numbers describe what a user of this project actually gets. See eval/README.md for how the
score works and what it does not tell you.
"""

from __future__ import annotations

import argparse
import contextlib
import importlib.metadata
import json
import os
import platform
import statistics
from dataclasses import asdict
from pathlib import Path

from PIL import Image

from street_scene_ocr.config import Settings
from street_scene_ocr.evaluation import LabelLine, score_image, summarize
from street_scene_ocr.postprocess import is_confident, to_traditional
from street_scene_ocr.service import EngineManager

HERE = Path(__file__).resolve().parent
DATA = HERE / "data"
SETS = {"photos": DATA / "photos", "synthetic": DATA / "synthetic"}
PACKAGES = ("easyocr", "torch", "rapidocr", "paddleocr", "paddlex", "onnxruntime", "opencv-contrib-python")


def load_set(folder: Path) -> list[tuple[str, Image.Image, list[LabelLine]]]:
    labels = json.loads((folder / "labels.json").read_text(encoding="utf-8"))
    return [
        (name, Image.open(folder / name).convert("RGB"), [LabelLine.from_dict(line) for line in lines])
        for name, lines in sorted(labels.items())
    ]


def versions() -> dict[str, str]:
    found = {}
    for package in PACKAGES:
        with contextlib.suppress(importlib.metadata.PackageNotFoundError):
            found[package] = importlib.metadata.version(package)
    return found


def cpu_name() -> str:
    try:
        for line in Path("/proc/cpuinfo").read_text().splitlines():
            if line.startswith("model name"):
                return line.split(":", 1)[1].strip()
    except OSError:
        pass
    return platform.processor() or platform.machine()


def run_engine(manager: EngineManager, engine: str, sets: dict, threshold: float) -> dict:
    manager.get(engine)  # load the models before timing anything
    first = next(iter(sets.values()))[0][1]
    manager.read(engine, first)  # one warm-up read; the first call of a model is always slower
    report = {"device": manager.get(engine).device, "sets": {}}
    for set_name, images in sets.items():
        scores, converted, times, details = [], [], [], []
        for name, image, labels in images:
            result = manager.read(engine, image, traditional=False)
            kept = [r for r in result.regions if is_confident(r, threshold)]
            score = score_image(kept, labels)
            scores.append(score)
            # The optional post-processing step, scored on the same engine output.
            converted.append(score_image(to_traditional(kept), labels))
            times.append(result.total_ms)
            details.append(
                {
                    "image": name,
                    "ms": result.total_ms,
                    "extra_regions": score.extra_regions,
                    "lines": [asdict(line) for line in score.lines],
                }
            )
            print(f"  {engine:10} {set_name:9} {name:28} {score.errors:3} errors / {score.characters} chars")
        summary = summarize(scores)
        report["sets"][set_name] = {
            **asdict(summary),
            "cer": round(summary.cer, 4),
            "cer_to_traditional": round(summarize(converted).cer, 4),
            "line_accuracy": round(summary.line_accuracy, 4),
            "median_ms": round(statistics.median(times), 1),
            "mean_ms": round(statistics.fmean(times), 1),
            "images_detail": details,
        }
    return report


def percent(value: float) -> str:
    return f"{value * 100:.1f}%"


def write_markdown(results: dict, path: Path) -> None:
    engines = results["engines"]
    machine = results["machine"]
    cpus = f"{machine['cpus_available']} of {machine['cpu_count']}"
    out = [
        "# Benchmark results",
        "",
        "Generated by `python eval/run.py`. Do not edit by hand; see [README.md](../README.md) for how to read it.",
        "",
        f"- Confidence threshold: {results['min_confidence']} (regions at or below it are dropped before scoring)",
        "- 'CER with OpenCC s2tw': the same readings after the optional Simplified-to-Traditional conversion",
        f"- Machine: {machine['cpu']}, {cpus} logical CPUs used (one thread each), Python {machine['python']}",
        f"- Packages: {', '.join(f'{k} {v}' for k, v in results['versions'].items())}",
        "",
    ]
    for set_name in SETS:
        rows = [(name, report["sets"][set_name], report["device"]) for name, report in engines.items()]
        if not rows:
            continue
        first = rows[0][1]
        size = f"{first['images']} images, {first['lines']} lines, {first['characters']} characters"
        out += [
            f"## {set_name.capitalize()}: {size}",
            "",
            "| Engine | CER (lower is better) | CER with OpenCC s2tw | Lines read exactly | Extra regions "
            "| Median time per image |",
            "|---|---:|---:|---:|---:|---:|",
        ]
        for name, s, device in rows:
            out.append(
                f"| {name} | {percent(s['cer'])} | {percent(s['cer_to_traditional'])} "
                f"| {s['exact_lines']}/{s['lines']} ({percent(s['line_accuracy'])}) "
                f"| {s['extra_regions']} | {s['median_ms'] / 1000:.2f} s ({device}) |"
            )
        out.append("")

    out += ["## Every photo line, side by side", "", "| Photo | Expected | " + " | ".join(engines) + " |"]
    out.append("|---|---|" + "---|" * len(engines))
    by_engine = {name: report["sets"]["photos"]["images_detail"] for name, report in engines.items()}
    first_engine = next(iter(by_engine.values()), [])
    for i, image in enumerate(first_engine):
        for j, line in enumerate(image["lines"]):
            cells = []
            for name in engines:
                read = by_engine[name][i]["lines"][j]
                mark = "✓" if read["errors"] == 0 else f"✗{read['errors']}"
                cells.append(f"{read['read'] or '—'} {mark}")
            out.append(f"| {image['image'].removesuffix('.jpg')} | {line['expected']} | " + " | ".join(cells) + " |")
    path.write_text("\n".join(out) + "\n", encoding="utf-8")


def main() -> None:
    parser = argparse.ArgumentParser(description="Score the OCR engines on eval/data.")
    parser.add_argument("--engines", nargs="*", help="engine names (default: every installed engine)")
    parser.add_argument("--min-confidence", type=float, help="threshold (default: the service default, 0.3)")
    parser.add_argument("--out", type=Path, default=HERE / "results", help="output folder (default eval/results)")
    args = parser.parse_args()

    settings = Settings.from_env()
    threshold = settings.min_confidence if args.min_confidence is None else args.min_confidence
    manager = EngineManager(settings)
    engines = args.engines or manager.installed
    sets = {name: load_set(folder) for name, folder in SETS.items()}

    results = {
        "min_confidence": threshold,
        "max_image_side": settings.max_image_side,
        "machine": {
            "cpu": cpu_name(),
            "cpu_count": os.cpu_count(),
            "cpus_available": settings.threads,
            "python": platform.python_version(),
        },
        "versions": versions(),
        "engines": {},
    }
    for engine in engines:
        print(f"{engine}: loading", flush=True)
        results["engines"][engine] = run_engine(manager, engine, sets, threshold)

    args.out.mkdir(parents=True, exist_ok=True)
    (args.out / "results.json").write_text(json.dumps(results, ensure_ascii=False, indent=1) + "\n", encoding="utf-8")
    write_markdown(results, args.out / "results.md")
    for engine, report in results["engines"].items():
        cells = ", ".join(f"{name} CER {percent(s['cer'])}" for name, s in report["sets"].items())
        print(f"{engine}: {cells}")


if __name__ == "__main__":
    main()
