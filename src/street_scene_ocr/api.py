"""The web service: a JSON API, an annotated-image endpoint and the upload page.

Interactive API docs are generated by FastAPI at ``/docs`` (Swagger UI) and ``/redoc``.
"""

from __future__ import annotations

import io
import socket
from typing import Annotated

from fastapi import FastAPI, File, Form, HTTPException, Request, UploadFile
from fastapi.concurrency import run_in_threadpool
from fastapi.responses import FileResponse, Response
from fastapi.staticfiles import StaticFiles
from PIL import Image
from pydantic import BaseModel, Field

from . import __version__
from .config import WEB_DIR, Settings
from .engines import EngineError
from .imaging import InvalidImage, decode_image
from .postprocess import is_confident
from .render import annotate
from .service import EngineManager, EngineNotInstalled, OcrResult, UnknownEngine

# Every response says which container answered, so the Traefik load-balancing demo is visible.
SERVED_BY_HEADER = "X-Served-By"

# Form fields shared by the two OCR endpoints.
ImageField = Annotated[UploadFile, File(description="png, jpg or jpeg image")]
EngineField = Annotated[str | None, Form(description="engine name from /api/engines; empty uses the default")]
ThresholdField = Annotated[
    float | None,
    Form(ge=0, le=1, description="regions above this confidence count as confident (server default 0.3)"),
]
ShowUnsureField = Annotated[bool, Form(description="also draw regions at or below the threshold")]
TraditionalField = Annotated[
    bool | None,
    Form(description="convert Simplified characters to Traditional with OpenCC (server default: off)"),
]


class Region(BaseModel):
    text: str
    confidence: float = Field(description="0 to 1, how sure the engine is")
    confident: bool = Field(description="confidence is above the requested threshold")
    polygon: list[tuple[float, float]] = Field(description="corners in image pixels, clockwise")
    bbox: tuple[float, float, float, float] = Field(description="left, top, right, bottom")


class OcrResponse(BaseModel):
    engine: str
    device: str
    width: int
    height: int
    min_confidence: float
    regions: list[Region] = Field(description="in reading order: rows top to bottom, left to right")
    text: str = Field(description="confident regions joined with new lines, in reading order")
    to_traditional: bool = Field(description="Simplified characters were converted to Traditional")
    stages_ms: dict[str, float] = Field(description="time per pipeline stage, when the engine reports it")
    total_ms: float
    served_by: str


class EngineDescription(BaseModel):
    name: str
    title: str
    summary: str
    homepage: str
    installed: bool
    missing: list[str]
    loaded: bool
    device: str | None


class EnginesResponse(BaseModel):
    default_engine: str | None
    default_min_confidence: float
    default_to_traditional: bool
    max_upload_mb: int
    allowed_extensions: list[str]
    engines: list[EngineDescription]


def create_app(settings: Settings | None = None, manager: EngineManager | None = None) -> FastAPI:
    settings = settings or Settings.from_env()
    manager = manager or EngineManager(settings)
    hostname = socket.gethostname()

    app = FastAPI(
        title="street-scene-ocr",
        version=__version__,
        description=(
            "Find and read text in street photos (Traditional Chinese and English) with several OCR "
            "engines behind one interface. Upload an image to `/api/ocr` for JSON or to "
            "`/api/ocr/annotated` for a PNG with the boxes drawn on it."
        ),
    )

    @app.middleware("http")
    async def add_served_by(request: Request, call_next):
        response = await call_next(request)
        response.headers[SERVED_BY_HEADER] = hostname
        return response

    async def load_upload(file: UploadFile) -> Image.Image:
        name = file.filename or ""
        extension = name.rsplit(".", 1)[-1].lower() if "." in name else ""
        if extension not in settings.allowed_extensions:
            # Same wording as the 2021 page.
            raise HTTPException(400, f"Allowed image types are -> {', '.join(settings.allowed_extensions)}")
        data = await file.read(settings.max_upload_bytes + 1)
        if len(data) > settings.max_upload_bytes:
            raise HTTPException(413, f"The image is larger than {settings.max_upload_mb} MB")
        try:
            return await run_in_threadpool(decode_image, data)  # decoding a big photo takes a moment
        except InvalidImage as exc:
            raise HTTPException(422, str(exc)) from exc

    def run(engine: str | None, image: Image.Image, traditional: bool | None) -> OcrResult:
        name = engine or manager.default_engine()
        if name is None:
            raise HTTPException(503, "no OCR engine is installed")
        try:
            return manager.read(name, image, traditional)
        except UnknownEngine as exc:
            raise HTTPException(404, str(exc)) from exc
        except EngineNotInstalled as exc:
            raise HTTPException(409, str(exc)) from exc
        except EngineError as exc:
            raise HTTPException(500, str(exc)) from exc

    @app.get("/api/engines", response_model=EnginesResponse, tags=["ocr"])
    def list_engines() -> EnginesResponse:
        """Which engines this server knows, whether they are installed and whether they are loaded."""
        return EnginesResponse(
            default_engine=manager.default_engine(),
            default_min_confidence=settings.min_confidence,
            default_to_traditional=settings.to_traditional,
            max_upload_mb=settings.max_upload_mb,
            allowed_extensions=list(settings.allowed_extensions),
            engines=[EngineDescription(**{**vars(info), "missing": list(info.missing)}) for info in manager.describe()],
        )

    @app.post("/api/ocr", response_model=OcrResponse, tags=["ocr"])
    async def read_text(
        file: ImageField,
        engine: EngineField = None,
        min_confidence: ThresholdField = None,
        to_traditional: TraditionalField = None,
    ) -> OcrResponse:
        """Read the text in an image and return every region with its box and confidence."""
        image = await load_upload(file)
        threshold = settings.min_confidence if min_confidence is None else min_confidence
        result = await run_in_threadpool(run, engine, image, to_traditional)
        regions = [
            Region(
                text=r.text,
                confidence=round(r.confidence, 4),
                confident=is_confident(r, threshold),
                polygon=[(round(x, 1), round(y, 1)) for x, y in r.polygon],
                bbox=tuple(round(v, 1) for v in r.bbox),
            )
            for r in result.regions
        ]
        return OcrResponse(
            engine=result.engine,
            device=result.device,
            width=result.width,
            height=result.height,
            min_confidence=threshold,
            regions=regions,
            text="\n".join(r.text for r in regions if r.confident),
            to_traditional=result.traditional,
            stages_ms=result.stages_ms,
            total_ms=result.total_ms,
            served_by=hostname,
        )

    @app.post(
        "/api/ocr/annotated",
        tags=["ocr"],
        response_class=Response,
        responses={200: {"content": {"image/png": {}}, "description": "the image with boxes and labels"}},
    )
    async def read_text_annotated(
        file: ImageField,
        engine: EngineField = None,
        min_confidence: ThresholdField = None,
        show_unsure: ShowUnsureField = True,
        to_traditional: TraditionalField = None,
    ) -> Response:
        """Read the text and return the image with green (confident) and red (unsure) outlines and labels."""
        image = await load_upload(file)
        threshold = settings.min_confidence if min_confidence is None else min_confidence
        result = await run_in_threadpool(run, engine, image, to_traditional)
        drawn = await run_in_threadpool(annotate, image, result.regions, threshold, settings.font_path, show_unsure)
        buffer = io.BytesIO()
        drawn.save(buffer, "PNG")
        return Response(buffer.getvalue(), media_type="image/png")

    @app.get("/healthz", tags=["service"])
    def health() -> dict[str, str]:
        """Liveness check for Docker and Traefik."""
        return {"status": "ok", "served_by": hostname}

    @app.get("/", include_in_schema=False)
    def index() -> FileResponse:
        return FileResponse(WEB_DIR / "index.html")

    app.mount("/static", StaticFiles(directory=WEB_DIR), name="static")
    return app
